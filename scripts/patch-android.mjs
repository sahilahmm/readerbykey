// Run after `npx cap add android`. Makes the generated Android project look like Reader:
//  - launcher icon + splash use the Mocha Bean / Creamy Latte look (no Capacitor logo)
//  - the app label stays exactly "Reader" (Capacitor already writes it from appName)
//  - versionCode / versionName come from the build number so updates install cleanly
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const res = join(root, "android", "app", "src", "main", "res");
const gradleFile = join(root, "android", "app", "build.gradle");

if (!existsSync(res)) {
  console.error("android/ not found. Run `npx cap add android` first.");
  process.exit(1);
}

// 1. icons (generated by resources/make-icons.py, committed)
cpSync(join(root, "resources", "android", "res"), res, { recursive: true });

// 2. adaptive-icon background color = Mocha Bean
writeFileSync(
  join(res, "values", "ic_launcher_background.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#7A553A</color>
</resources>
`
);

// 3. drop Capacitor's placeholder art (logo splash, robot foreground, grid background)
for (const rel of [
  "drawable/splash.png",
  "drawable/ic_launcher_background.xml",
  "drawable-v24/ic_launcher_foreground.xml",
  ...["land", "port"].flatMap((o) => ["mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"].map((d) => `drawable-${o}-${d}/splash.png`)),
]) {
  rmSync(join(res, rel), { force: true });
}

// 4. launch screen: plain Mocha Bean with the cream "R"
const stylesPath = join(res, "values", "styles.xml");
let styles = readFileSync(stylesPath, "utf8");
const launch = /<style name="AppTheme\.NoActionBarLaunch"[\s\S]*?<\/style>/;
if (!launch.test(styles)) throw new Error("Launch theme not found in styles.xml");
styles = styles.replace(
  launch,
  `<style name="AppTheme.NoActionBarLaunch" parent="Theme.SplashScreen">
        <item name="windowSplashScreenBackground">@color/ic_launcher_background</item>
        <item name="windowSplashScreenAnimatedIcon">@mipmap/ic_launcher_foreground</item>
        <item name="android:background">@color/ic_launcher_background</item>
    </style>`
);
writeFileSync(stylesPath, styles);

// 5. "Open with": make Reader show up when you tap a PDF in WhatsApp, Files, a browser, etc.
const manifestPath = join(root, "android", "app", "src", "main", "AndroidManifest.xml");
let manifest = readFileSync(manifestPath, "utf8");
if (!manifest.includes("android:mimeType=\"application/pdf\"")) {
  const pdfFilter = `
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />
                <data android:scheme="file" />
                <data android:mimeType="application/pdf" />
            </intent-filter>
`;
  if (!manifest.includes("</activity>")) throw new Error("Activity not found in AndroidManifest.xml");
  manifest = manifest.replace("</activity>", `${pdfFilter}\n        </activity>`);
  // the on-screen keyboard resizes the page, so the pill rises above it while renaming
  if (!manifest.includes("windowSoftInputMode")) {
    manifest = manifest.replace('android:launchMode="singleTask"', 'android:launchMode="singleTask"\n            android:windowSoftInputMode="adjustResize"');
  }
  writeFileSync(manifestPath, manifest);
}

// 6. version numbers (VERSION_NAME comes from the VERSION file, VERSION_CODE from the build number)
const code = parseInt(process.env.VERSION_CODE || "1", 10);
const name = process.env.VERSION_NAME || "1.0";
let gradle = readFileSync(gradleFile, "utf8");
gradle = gradle.replace(/versionCode \d+/, `versionCode ${code}`).replace(/versionName "[^"]*"/, `versionName "${name}"`);
writeFileSync(gradleFile, gradle);

console.log(`Patched Android project (versionCode ${code}, versionName ${name})`);
